const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const output = process.argv[2] || path.join(root, "web", "ide-resources.js");

function posixPath(parts) {
  return parts.join("/");
}

function sourceFiles() {
  const includeDir = path.join(root, "include");
  const headers = fs.readdirSync(includeDir)
    .filter(name => name.endsWith(".h"))
    .map(name => ({
      src: posixPath(["include", name]),
      resource: posixPath(["", "include", name])
    }));
  headers.push({
    src: "tcclib.h",
    resource: "/include/tcclib.h"
  });
  return headers.sort((a, b) => a.resource.localeCompare(b.resource));
}

const files = {};
for (const file of sourceFiles()) {
  files[file.resource] = fs.readFileSync(path.join(root, file.src), "utf8");
}

const body = `/* Generated by web/build-ide-resources.js. */
(function (root, factory) {
  const resources = factory();
  if (typeof module === "object" && module.exports)
    module.exports = resources;
  else
    root.TccWasmIdeResources = resources;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

  return {
    files: ${JSON.stringify(files, null, 4)}
  };
});
`;

fs.writeFileSync(output, body);
