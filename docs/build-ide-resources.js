const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const output = process.argv[2] || path.join(root, "docs", "ide-resources.js");

function posixPath(parts) {
  return parts.join("/");
}

function sourceFiles() {
  const includeDir = path.join(root, "include");
  function walk(dir, rel) {
    const out = [];
    for (const name of fs.readdirSync(dir)) {
      const full = path.join(dir, name);
      const childRel = rel.concat(name);
      const st = fs.statSync(full);
      if (st.isDirectory())
        out.push(...walk(full, childRel));
      else if (name.endsWith(".h"))
        out.push({
          src: posixPath(["include"].concat(childRel)),
          resource: posixPath(["", "include"].concat(childRel))
        });
    }
    return out;
  }
  const headers = walk(includeDir, []);
  headers.push({
    src: "tcclib.h",
    resource: "/include/tcclib.h"
  });
  return headers.sort((a, b) => a.resource.localeCompare(b.resource));
}

const files = {};
for (const file of sourceFiles()) {
  files[file.resource] = fs.readFileSync(path.join(root, file.src)).toString("base64");
}

const body = `/* Generated by docs/build-ide-resources.js. */
(function (root, factory) {
  const resources = factory();
  if (typeof module === "object" && module.exports)
    module.exports = resources;
  else
    root.TccWasmIdeResources = resources;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

  return {
    encoding: "base64",
    files: ${JSON.stringify(files, null, 4)}
  };
});
`;

fs.writeFileSync(output, body);
